const dictionaries: Record<Lang, Record<TKey, string>> = { en, fr };

interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

export const useLangStore = create<LangState>()(
  persist((set) => ({ lang: "fr", setLang: (lang) => set({ lang }) }), { name: "riskyc-pos-lang-v1" })
);

export type TVars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: TVars): string {
  let text: string = dictionaries[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{{${name}}}`).join(String(value));
  }
  return text;
}

/** For code outside React (stores, API helpers): the language active right now. */
export function t(key: TKey, vars?: TVars): string {
  return translate(useLangStore.getState().lang, key, vars);
}

export function localeOf(lang: Lang): string {
  return lang === "fr" ? "fr-FR" : "en-GB";
}

/** The active-language `t`, plus the matching locale for dates and numbers. Re-renders when the language changes. */
export function useT() {
  const lang = useLangStore((s) => s.lang);
  const tr = useCallback((key: TKey, vars?: TVars) => translate(lang, key, vars), [lang]);
  return { t: tr, lang, locale: localeOf(lang) };
}
